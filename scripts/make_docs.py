from __future__ import annotations

from pathlib import Path

import fitz  # PyMuPDF
from docx import Document
from docx.shared import Pt

RAW = Path(__file__).resolve().parents[1] / "data" / "raw"


def make_pdf(path: Path, title: str, paragraphs: list[tuple[str, str]]) -> None:
    doc = fitz.open()
    page = doc.new_page(width=595, height=842)  # A4
    y = 50
    page.insert_text((50, y), title, fontsize=16, fontname="helv")
    y += 30
    for heading, text in paragraphs:
        if y > 780:
            page = doc.new_page(width=595, height=842)
            y = 50
        if heading:
            page.insert_text((50, y), heading, fontsize=12, fontname="helv")
            y += 20
        for line in _wrap(text, 90):
            if y > 800:
                page = doc.new_page(width=595, height=842)
                y = 50
            page.insert_text((50, y), line, fontsize=10, fontname="helv")
            y += 14
        y += 8
    doc.save(str(path))
    doc.close()


def _wrap(text: str, width: int) -> list[str]:
    words = text.split()
    lines: list[str] = []
    cur: list[str] = []
    for w in words:
        if sum(len(x) + 1 for x in cur) + len(w) > width:
            lines.append(" ".join(cur))
            cur = [w]
        else:
            cur.append(w)
    if cur:
        lines.append(" ".join(cur))
    return lines


def make_docx(path: Path, title: str, sections: list[tuple[str, list[str]]]) -> None:
    doc = Document()
    doc.add_heading(title, level=0)
    for heading, paragraphs in sections:
        doc.add_heading(heading, level=1)
        for p in paragraphs:
            para = doc.add_paragraph(p)
            para.style.font.size = Pt(11)
    doc.save(str(path))


