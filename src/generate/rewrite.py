"""Query rewriting: переписывание вопроса с учётом истории диалога.

Проблема: follow-up «А в командировке?» эмбеддится как есть — ретривер
не находит «регламент командировок», потому что в вопросе нет слова
«командировка». Решение: перед поиском LLM переписывает последний вопрос
в самодостаточный («Каковы правила направления в командировку?»).

Рерайтинг дешёвый (один короткий вызов LLM), но выполняется только когда
история непустая — первый вопрос уже самодостаточен.
"""
from __future__ import annotations

REWRITE_SYSTEM = """Ты — модуль поиска по документам. Твоя задача — переписать
последний вопрос пользователя в самодостаточный поисковый запрос, используя
контекст предыдущих сообщений диалога.

Правила:
1. Сохрани суть вопроса, но раскрой местоимения и отсылки («а в нём?»,
   «сколько там дней?») через контекст истории.
2. Добавь ключевые термины из истории, если вопрос их подразумевает.
3. Не добавляй ничего, чего нет в диалоге.
4. Ответь ТОЛЬКО переписанным запросом, без пояснений."""


def build_rewrite_messages(query: str, history: list[dict]) -> list[dict]:
    """Сообщения для LLM-рерайтинга: история + последний вопрос."""
    turns = []
    for m in history[-6:]:  # последние 3 пары достаточно
        role = "Пользователь" if m.get("role") == "user" else "Ассистент"
        turns.append(f"{role}: {m.get('content', '')}")
    dialogue = "\n".join(turns) if turns else "(история пуста)"
    user = (
        f"История диалога:\n{dialogue}\n\n"
        f"Последний вопрос: {query}\n\n"
        f"Перепиши его в самодостаточный поисковый запрос."
    )
    return [
        {"role": "system", "content": REWRITE_SYSTEM},
        {"role": "user", "content": user},
    ]


def extract_rewritten(text: str, fallback: str) -> str:
    """Достаёт запрос из ответа LLM; при мусоре — исходный вопрос."""
    t = (text or "").strip()
    if not t or len(t) > 500:
        return fallback
    # Однострочный запрос — берём первую содержательную строку
    for line in t.splitlines():
        line = line.strip().strip('"«»')
        if len(line) >= 5:
            return line
    return fallback
